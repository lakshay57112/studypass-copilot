-- Findings and audit trail (written by the str-report skill / SP_DRAFT_FINDING)
CREATE TABLE IF NOT EXISTS CASE_FINDINGS (
  FINDING_ID VARCHAR DEFAULT UUID_STRING(), CUSTOMER_ID VARCHAR, RISK_SCORE NUMBER, RISK_BAND VARCHAR,
  SIGNALS ARRAY, EVIDENCE_IDS ARRAY, POLICY_CLAUSES ARRAY, NARRATIVE VARCHAR,
  STATUS VARCHAR DEFAULT 'DRAFT_PENDING_REVIEW', CREATED_BY VARCHAR DEFAULT CURRENT_USER(),
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), REVIEWED_BY VARCHAR, REVIEWED_AT TIMESTAMP_NTZ);

CREATE TABLE IF NOT EXISTS AUDIT_LOG (
  EVENT_ID VARCHAR DEFAULT UUID_STRING(), EVENT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  ACTOR VARCHAR DEFAULT CURRENT_USER(), ROLE_NAME VARCHAR DEFAULT CURRENT_ROLE(),
  ACTION VARCHAR, CUSTOMER_ID VARCHAR, DETAILS VARIANT);
